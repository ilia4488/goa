const sum =(num1,num2)=>{
    return num1+num2
}
const multiply = (num1,num2)=>{
    return num1*num2
}
const divide =(num1,num2)=>{
    return num1/num2
}
const minus = (num1,num2)=>{
    return num1-num2
}
const square =(num1)=>{
    return num1**2
}
const perimeter = (num1,num2)=>{
    return (num1+num2)*2
}

module.exports = {
    sum,
    multiply,
    divide,
    minus,
    square,
    perimeter
} 