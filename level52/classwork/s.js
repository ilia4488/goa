// 1. .length - აბრუნებს სტრინგის სიგრძეს (სიმბოლოების რაოდენობას).
"hello".length;
"JS".length;

// 2. .charAt(index) - აბრუნებს მითითებულ ინდექსზე მყოფ სიმბოლოს.
"apple".charAt(0);
"code".charAt(2);

// 3. .at() - აბრუნებს სიმბოლოს ინდექსის მიხედვით. მუშაობს უარყოფით ინდექსებზეც (ბოლოდან ითვლის).
"banana".at(1);
"javascript".at(-1);

// 4. .slice(startIndex, endIndex) - ჭრის სტრინგის ნაწილს დაწყების ინდექსიდან დასრულების ინდექსამდე (დასასრულს არ თვლის).
"frontend".slice(0, 4);
"developer".slice(3, 7);

// 5. .toUpperCase() - სტრინგის ყველა ასოს აქცევს დიდ ასოდ.
"hello".toUpperCase();
"web".toUpperCase();

// 6. .toLowerCase() - სტრინგის ყველა ასოს აქცევს პატარა ასოდ.
"HELLO".toLowerCase();
"HTML".toLowerCase();

// 7. .trim() - აშორებს გამოტოვებულ ადგილებს (სფეისებს) სტრინგის დასაწყისიდან და ბოლოდან.
"  hello  ".trim();
" js ".trim();

// 8. .trimStart() - აშორებს გამოტოვებულ ადგილებს მხოლოდ სტრინგის დასაწყისიდან.
"  hello".trimStart();
" code".trimStart();

// 9. .trimEnd() - აშორებს გამოტოვებულ ადგილებს მხოლოდ სტრინგის ბოლოდან.
"hello  ".trimEnd();
"web ".trimEnd();

// 10. .repeat() - აკოპირებს სტრინგს მითითებულჯერ.
"hi".repeat(3);
"A".repeat(5);

// 11. .replace() - ანაცვლებს პირველივე ნაპოვნ სიტყვას ან სიმბოლოს ახლით.
"red apple".replace("red", "green");
"no no".replace("no", "yes");

// 12. .replaceAll() - ანაცვლებს ყველა ნაპოვნ სიტყვას ან სიმბოლოს ახლით.
"no no".replaceAll("no", "yes");
"1-2-3".replaceAll("-", "/");

// 13. .split() - ყოფს სტრინგს მასივად მითითებული გამყოფის მიხედვით.
"hello world".split(" ");
"a,b,c".split(",");

// .at() მეთოდს შეუძლია მიიღოს უარყოფითი ინდექსი და დააბრუნოს სიმბოლო ბოლოდან (მაგალითად, -1 არის ბოლო სიმბოლო).
// .charAt() უარყოფით ინდექსზე ყოველთვის აბრუნებს ცარიელ სტრინგს ("").

"hello".at(-1);      // დააბრუნებს "o"
"hello".charAt(-1);  // დააბრუნებს ""